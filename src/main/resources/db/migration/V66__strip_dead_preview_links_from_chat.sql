-- #391 이전 승인 메시지에 박혀 있던 죽은 preview 링크를 이력에서 지운다 (#405).
--
-- POST /preview-sessions/{id}/access 가 accessToken 을 회전시켜 이전 주소를 죽인다(#77 G4).
-- 사용자가 화면에서 프리뷰를 여는 것이 곧 그 호출이므로, 메시지에 박힌 주소는 프리뷰를 한 번
-- 연 순간부터 404다. #391 이 새 메시지에서 그 줄을 뺐지만 이미 나간 메시지는 대화 이력에
-- 그대로 남아 있고, 이력은 영구라서 옛 대화를 여는 사용자는 계속 그 링크를 본다.
--
-- ⚠️ 순진한 LIKE '%- preview:%' 는 멀쩡한 줄을 파괴한다.
--
-- content 의 콜레이션이 utf8mb4_unicode_ci 라 대소문자를 구분하지 않는다. 그래서 그 조건은
-- 상태 표시 메시지의 다음 줄에도 매치된다 — URL 도 없고 잘못된 것도 없는 정상적인 줄이다.
--
--     서버/서비스 상태
--     - Preview: 실행 중인 preview 없음
--
-- 운영에서 실제로 이 행(message_id 79)이 함께 걸렸다. 그래서 조건을 둘로 건다.
--   1) 정규식이 https?:// 를 요구한다 — URL 이 없는 줄은 어떤 콜레이션에서도 매치되지 않는다
--   2) WHERE 가 LIKE BINARY 로 대소문자를 구분한다 — 갱신 대상 자체를 좁힌다
--
-- 치환은 앞뒤 개행을 포함해 잡고 개행 하나로 되돌린다. 그 줄만 사라지고 주변 줄 구조는 그대로다.
-- 운영 8건 모두 그 줄이 메시지 중간에 있어(뒤에 '- [N] RESULT:' 또는 '- 저장소 이름' 이 온다)
-- 끝줄 예외를 다룰 필요가 없다. 끝에 있는 경우에도 이 패턴은 매치되지 않아 그냥 남으므로
-- 데이터를 망치지 않는다.
--
-- 드라이런(운영, 읽기만): 대상 8건 · 제거 길이 전부 정확히 117자
--   = '- preview: '(11) + 주소(105) + 개행(1)
-- 117자가 8건 모두 같은 것이 신호다 — 행마다 정확히 한 번 매치되고 다른 것은 건드리지 않았다.
--
-- 안내 문구로 바꾸지 않는 이유: #391 에서 줄 전체 제거를 택했다. 승인 카드가 이미 화면에
-- 프리뷰와 함께 뜨므로 주소도 안내도 중복이고, 주소는 거기에 해롭기까지 했다. 이력에 다른
-- 판단을 적용할 이유가 없고, 없던 문장을 새로 넣는 것은 기록을 더 고치는 것이다.
UPDATE chat_messages
SET content = REGEXP_REPLACE(content, '\n- preview: https?://[^\n]*\n', '\n')
WHERE content LIKE BINARY '%- preview: http%';
