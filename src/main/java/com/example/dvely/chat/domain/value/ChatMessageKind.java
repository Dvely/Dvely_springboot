package com.example.dvely.chat.domain.value;

/**
 * 어시스턴트 메시지의 <b>종류</b>. 화면이 문구를 읽지 않고도 그 줄이 무엇인지 알게 한다.
 *
 * <p>이 값이 없으면 FE 는 본문 문자열로 의미를 추론할 수밖에 없고, 그 패턴은 이 제품에서 이미 한 번
 * 사고를 냈다 — 본문에 "승인 후 실행" 이 들어 있으면 승인 버튼을 붙이던 시절, 모델이 그 문장을
 * 지어내자 존재하지 않는 버튼이 떴다. 서버가 문구를 한 글자 다듬는 것만으로도 조용히 깨지는 결합이라
 * 종류를 값으로 준다.</p>
 *
 * <p><b>읽는 쪽 계약:</b> {@code null} 은 "종류가 지정되지 않음"(이 필드 도입 이전에 쌓인 줄과 순수
 * 대화 답변)이고, <b>모르는 값이 오면 무시하고 평범한 어시스턴트 줄로 그릴 것</b> — 종류는 늘어난다.</p>
 */
public enum ChatMessageKind {

    /** 에이전트가 만들어낸 결과·답변. 모델이 쓴 글이라 형식이 자유롭다. */
    AGENT_RESULT,

    /** 진행·전이 안내. 우리가 쓴 운영 문구다("승인 정책에 따라 작업을 시작합니다"). */
    TASK_PROGRESS,

    /** 승인이 필요하다는 안내. 대개 바로 아래 승인 카드가 붙는다. */
    APPROVAL_REQUESTED,

    /** 사용자 입력이 필요하다는 안내(되묻기 질문). */
    INPUT_REQUIRED,

    /** 사용자가 되묻기에 답한 내용의 기록. 답변 폼은 사라지므로 이 줄이 영구 기록이다. */
    CLARIFICATION_ANSWER,

    /** 작업이 실패했다. */
    TASK_FAILED,

    /** 작업이 취소되거나 되돌릴 수 없이 종료됐다. */
    TASK_CANCELLED
}
